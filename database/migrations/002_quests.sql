-- Segurança do Supabase (mesmo padrão das migrations de autenticação e social).
-- A aplicação acessa o banco pela connection string do pooler (role privilegiada),
-- que não é afetada por RLS. RLS sem policies + REVOKE bloqueiam o acesso pela
-- Data API (PostgREST) com as chaves anon/authenticated.
ALTER TABLE public.quest_categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.quests           ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.quest_categories, public.quests FROM anon, authenticated;
