-- Categorias definidas pelo sistema: cada uma fixa a dificuldade e o XP base.
-- O estudante escolhe a categoria, mas não altera dificuldade nem XP.
CREATE TABLE IF NOT EXISTS public.quest_categories (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT    NOT NULL,
  difficulty TEXT    NOT NULL,
  base_xp    INTEGER NOT NULL,
  CONSTRAINT quest_categories_name_key UNIQUE (name),
  CONSTRAINT quest_categories_difficulty_check CHECK (difficulty IN ('facil', 'medio', 'dificil')),
  CONSTRAINT quest_categories_base_xp_check CHECK (base_xp > 0)
);

CREATE TABLE IF NOT EXISTS public.quests (
  id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id     BIGINT  NOT NULL,
  category_id BIGINT  NOT NULL,
  title       TEXT    NOT NULL,
  description TEXT,
  deadline    DATE    NOT NULL,
  -- XP já calculado no momento da criação (categoria, ou 3x em quest de guilda):
  -- mudar a categoria depois não altera quests existentes.
  xp          INTEGER NOT NULL,
  status      TEXT    NOT NULL DEFAULT 'pendente',
  is_guild    BOOLEAN NOT NULL DEFAULT FALSE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT quests_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES public.users (id) ON DELETE CASCADE,
  CONSTRAINT quests_category_id_fkey
    FOREIGN KEY (category_id) REFERENCES public.quest_categories (id),
  CONSTRAINT quests_xp_check CHECK (xp > 0),
  CONSTRAINT quests_status_check CHECK (status IN ('pendente', 'em_andamento', 'concluida'))
);

-- "Minhas quests" do usuário, ordenadas por prazo.
CREATE INDEX IF NOT EXISTS quests_user_id_deadline_idx ON public.quests (user_id, deadline);
CREATE INDEX IF NOT EXISTS quests_category_id_idx ON public.quests (category_id);

-- Categorias iniciais (idempotente). VALORES PROVISÓRIOS: a Squad 2 deve confirmar
