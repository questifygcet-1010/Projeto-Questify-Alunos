-- Squad 4 - Gerenciamento de Gold
-- Migracao para Supabase baseada em database/migrations/005_gold_ledger.sql.
-- Pre-requisito: public.users.

CREATE TABLE IF NOT EXISTS public.gold_ledger (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  type TEXT NOT NULL CHECK (type IN ('CREDIT', 'DEBIT')),
  amount INTEGER NOT NULL CHECK (amount > 0),
  source_event_id TEXT UNIQUE,
  description TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS gold_ledger_user_created_idx
  ON public.gold_ledger (user_id, created_at DESC, id DESC);

-- Seguranca: mesmo padrao das demais migrations do Supabase.
ALTER TABLE public.gold_ledger ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.gold_ledger FROM anon, authenticated;
